/** رقم السورة (1..114) التي تقع فيها صفحة المصحف المعطاة. */
export function surahAtPage(page: number): number {
  let n = 1;
  for (let i = 0; i < SURAH_START_PAGES.length; i++) {
    if (SURAH_START_PAGES[i] <= page) n = i + 1;
    else break;
  }
  return n;
}

export interface PageSegment { from: number; to: number; label: string }

/** مقاطع صفحات متساوية تغطّي المصحف كاملًا، بأسماء السور: «الفاتحة ١ - البقرة ١٠». */
export function pageSegments(size: number): PageSegment[] {
  const out: PageSegment[] = [];
  for (let from = 1; from <= MUSHAF_PAGES; from += size) {
    const to = Math.min(from + size - 1, MUSHAF_PAGES);
    const start = `${surahName(surahAtPage(from))} ${from}`;
    const end = `${surahName(surahAtPage(to))} ${to}`;
    out.push({ from, to, label: `${start} - ${end}` });
  }
  return out;
}

/** المراجعة الكبرى: مقاطع 10 صفحات. الصغرى: مقاطع 5 صفحات. */
export const MAJOR_SEGMENTS = pageSegments(10);
export const MINOR_SEGMENTS = pageSegments(5);
